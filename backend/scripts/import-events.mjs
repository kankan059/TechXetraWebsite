import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execSync } from 'node:child_process'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')

const jsonPath = path.join(rootDir, 'techxetra_2026_events.json')
const sqlOutputPath = path.join(__dirname, 'seed-events.sql')

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 50)
}

function escapeSql(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? '1' : '0'
  return `'${String(value).replace(/'/g, "''")}'`
}

function run() {
  console.log(`Reading event definitions from: ${jsonPath}`)
  const rawData = fs.readFileSync(jsonPath, 'utf8')
  const data = JSON.parse(rawData)

  const statements = [
    '-- Auto-generated event seed script for TechXetra 2026',
    '-- Generated by scripts/import-events.mjs',
    '',
  ]

  const now = 1793923200000 // Fixed fest base epoch ms (2026-11-06)

  // 1. Seed Users (Lead Coordinators)
  if (Array.isArray(data.users) && data.users.length > 0) {
    statements.push('-- Seed Lead Users')
    for (const u of data.users) {
      const sql = `INSERT OR IGNORE INTO users (
  id, email, name, phone, is_student, institution_name, role, can_review_payments, is_active, profile_completed_at, created_at, updated_at
) VALUES (
  ${escapeSql(u.id)},
  ${escapeSql(u.email)},
  ${escapeSql(u.name)},
  ${escapeSql(u.phone || null)},
  ${u.is_student ? 1 : 0},
  'Tezpur University',
  ${escapeSql(u.role || 'LEAD')},
  0,
  1,
  ${now},
  ${now},
  ${now}
);`
      statements.push(sql)
    }
    statements.push('')
  }

  // 2. Seed Events
  if (Array.isArray(data.events) && data.events.length > 0) {
    statements.push('-- Seed Events')
    for (const e of data.events) {
      const slug = slugify(e.name)
      const title = e.name
      const category = e.category
      const description = e.description || null
      const venue = e.venue || null
      const dayOfEvent = 1
      const startsAt = 1793923200000
      const endsAt = 1794009599999
      const status = 'OPEN'
      const isTeamEvent = e.is_team_event ? 1 : 0
      const minTeamSize = e.min_team_size || 1
      const maxTeamSize = e.max_team_size || 1

      let priceModel = 'FREE'
      let pricePaise = 0
      if (e.registration && e.registration.registration_fee_inr) {
        pricePaise = e.registration.registration_fee_inr * 100
        priceModel = e.registration.fee_type === 'Per team' ? 'PER_TEAM' : 'PER_PARTICIPANT'
      }

      const capacity = e.capacity || null

      // Build rich metadata object
      const metadataObj = {}
      const metaKeys = [
        'sub_category',
        'organizer',
        'tagline',
        'full_name',
        'eligibility',
        'rules',
        'tracks',
        'evaluation_criteria',
        'evaluation_metrics',
        'judging_criteria',
        'prizes',
        'prize_pool_inr',
        'timeline',
        'day_schedule',
        'rounds',
        'tools_allowed',
        'software_required',
        'materials_provided',
        'device_requirement',
        'coordinators',
        'leadership',
        'event_heads',
        'judge',
        'submitted_by',
        'mode',
        'tournament_format',
        'time_control',
        'equipment',
        'scrambling',
        'penalties',
        'timing_rules',
        'structure_and_rules',
        'duration_and_rules',
        'submission_requirements',
        'registration',
      ]

      for (const key of metaKeys) {
        if (e[key] !== undefined) {
          metadataObj[key] = e[key]
        }
      }

      const metadataJson = Object.keys(metadataObj).length > 0 ? JSON.stringify(metadataObj) : null

      const sql = `INSERT OR REPLACE INTO events (
  id, slug, title, category, description, venue, day_of_event, starts_at, ends_at,
  registration_closes_at, status, is_team_event, min_team_size, max_team_size,
  price_model, price_paise, student_price_paise, capacity, seats_taken,
  capacity_unit, scoring_enabled, scoring_status, max_rounds,
  volunteers_can_score, leaderboard_public, metadata, created_at, updated_at
) VALUES (
  ${escapeSql(e.id)},
  ${escapeSql(slug)},
  ${escapeSql(title)},
  ${escapeSql(category)},
  ${escapeSql(description)},
  ${escapeSql(venue)},
  ${dayOfEvent},
  ${startsAt},
  ${endsAt},
  NULL,
  ${escapeSql(status)},
  ${isTeamEvent},
  ${minTeamSize},
  ${maxTeamSize},
  ${escapeSql(priceModel)},
  ${pricePaise},
  NULL,
  ${escapeSql(capacity)},
  0,
  'SEATS',
  0,
  'NOT_APPLICABLE',
  1,
  0,
  0,
  ${escapeSql(metadataJson)},
  ${now},
  ${now}
);`
      statements.push(sql)
    }
    statements.push('')
  }

  // 3. Seed Event Staff
  if (Array.isArray(data.event_staff) && data.event_staff.length > 0) {
    statements.push('-- Seed Event Staff Assignments')
    for (const s of data.event_staff) {
      const sql = `INSERT OR REPLACE INTO event_staff (
  event_id, user_id, role, assigned_at, assigned_by
) VALUES (
  ${escapeSql(s.event_id)},
  ${escapeSql(s.user_id)},
  ${escapeSql(s.staff_role)},
  ${now},
  ${escapeSql(s.user_id)}
);`
      statements.push(sql)
    }
    statements.push('')
  }

  const outputSql = statements.join('\n')
  fs.writeFileSync(sqlOutputPath, outputSql, 'utf8')
  console.log(`Successfully generated SQL seed: ${sqlOutputPath}`)
  console.log(`- Seeded ${data.users?.length || 0} users`)
  console.log(`- Seeded ${data.events?.length || 0} events`)
  console.log(`- Seeded ${data.event_staff?.length || 0} staff assignments`)

  // Check if --apply flag is passed
  if (process.argv.includes('--apply')) {
    console.log('Applying seed directly to local D1 database via Wrangler...')
    execSync(`npx wrangler d1 execute DB --local --file="${sqlOutputPath}"`, {
      stdio: 'inherit',
      cwd: rootDir,
    })
    console.log('Local D1 database successfully seeded!')
  } else {
    console.log('\nTo apply this seed file to your local D1 database, run:')
    console.log(`npx wrangler d1 execute DB --local --file=scripts/seed-events.sql`)
  }
}

run()
